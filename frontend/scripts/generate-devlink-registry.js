/**
 * Generates `devlink/componentRegistry.ts` after a Webflow devlink export.
 *
 * Scans all `.tsx` component files in `devlink/` (recursively, excluding
 * `webflow_modules/` and `css/` and infrastructure files), extracts exported
 * component names via the `export function` pattern, and generates a
 * TypeScript registry mapping component names to their static imports.
 *
 * Used by `src/utils/getDevlinkComponent.ts` for locale-aware component
 * resolution (swapping En/De prefixes based on the current locale).
 *
 * Run this script immediately after `npx webflow devlink export`.
 */

const fs = require("fs");
const path = require("path");

const devlinkDir = path.join(__dirname, "..", "devlink");

if (!fs.existsSync(devlinkDir)) {
  console.warn(
    "generate-devlink-registry: devlink/ directory not found — skipping (export may have failed)"
  );
  process.exit(0);
}

// Generate devlink/componentRegistry.ts.
// Scans all .tsx component files in devlink/ (recursively, excluding
// webflow_modules/ and css/ and infrastructure files), extracts exported
// component names via the `export function` pattern, and generates a
// registry mapping component names to their static imports.
const INFRASTRUCTURE_FILES = new Set([
  "DevLinkProvider.tsx",
  "devlinkScope.ts",
  "ix3-interactions.tsx",
]);
const SKIP_DIRS = new Set(["webflow_modules", "css"]);
const FUNCTION_EXPORT_REGEX = /^export function (\w+)/m;
const registryEntries = [];

function walkTsxFiles(dir, relPath = "") {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    const rel = relPath ? `${relPath}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) {
        walkTsxFiles(fullPath, rel);
      }
    } else if (entry.name.endsWith(".tsx") && !INFRASTRUCTURE_FILES.has(entry.name)) {
      const content = fs.readFileSync(fullPath, "utf8");
      const match = content.match(FUNCTION_EXPORT_REGEX);
      if (match) {
        const componentName = match[1];
        const importPath = "./" + rel.replace(/\.tsx$/, "");
        registryEntries.push({ componentName, importPath });
      }
    }
  }
}

walkTsxFiles(devlinkDir);

registryEntries.sort((a, b) => a.componentName.localeCompare(b.componentName));

const registryLines = [];
registryLines.push(
  "// Auto-generated by scripts/generate-devlink-registry.js — do not edit manually.",
  "// Run `node scripts/generate-devlink-registry.js` after `npx webflow devlink export` to regenerate.",
  ""
);

for (const { componentName, importPath } of registryEntries) {
  registryLines.push(`import { ${componentName} } from "${importPath}";`);
}

registryLines.push("");

const mapEntries = registryEntries
  .map(({ componentName }) => `  "${componentName}": ${componentName},`)
  .join("\n");

registryLines.push(
  "export const componentRegistry: Record<string, React.ComponentType<any>> = {",
  mapEntries,
  "};",
  ""
);

const registryPath = path.join(devlinkDir, "componentRegistry.ts");
fs.writeFileSync(registryPath, registryLines.join("\n"), "utf8");
console.log(
  `generate-devlink-registry: generated componentRegistry.ts with ${registryEntries.length} components`
);
