"""
Rich-text images inside stored HTML (spec 20260708_1302).

Before an entity is saved, every image block in its HTML is resolved against
the database (:func:`resolve_rich_text_images`): images the user may not use
are removed, and the image attributes are rewritten from the stored image, so
the saved URLs are always generated by the server. After the save,
:func:`sync_project_description_usages` records which images the entity uses,
based on all language versions.
"""

from html.parser import HTMLParser

from climateconnect_api.models import RichTextImage, RichTextImageUsage
from climateconnect_api.utility.html import (
    PROJECT_DESCRIPTION_ALLOWED_ATTRIBUTES,
    PROJECT_DESCRIPTION_ALLOWED_TAGS,
    RICH_TEXT_IMAGE_ALIGN_CLASSES,
    RICH_TEXT_IMAGE_SIZE_CLASSES,
    RichTextImageBlock,
    sanitize_html,
)
from climateconnect_api.utility.rich_text_images import variant_urls

MAX_IMAGES_PER_TEXT = 10
MAX_ALT_TEXT_LENGTH = 150
DEFAULT_SIZE_CLASS = "image-size-full"
DEFAULT_ALIGN_CLASS = "image-align-center"
# Widest slot per size on desktop (the column is at most 1168 px wide), the
# share of the screen per size on phones and the phone breakpoint. Same values
# as sizesAttribute in the frontend's richTextImageStyles.ts; keep both in sync.
DESKTOP_SLOT = {
    "image-size-small": 390,
    "image-size-medium": 584,
    "image-size-full": 1168,
}
MOBILE_SLOT_VW = {
    "image-size-small": 50,
    "image-size-medium": 75,
    "image-size-full": 100,
}
MOBILE_BREAKPOINT = 600


class RichTextImageHtmlError(Exception):
    """The HTML cannot be saved (e.g. too many images). ``message`` is user-facing."""

    def __init__(self, message):
        super().__init__(message)
        self.message = message


class _ImageIdParser(HTMLParser):
    """Collect the data-image-id of every <img>."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids = []

    def handle_starttag(self, tag, attrs):
        image_id = dict(attrs).get("data-image-id") if tag == "img" else None
        if image_id and image_id.isdigit():
            self.ids.append(int(image_id))


def _image_ids(html_input):
    parser = _ImageIdParser()
    parser.feed(html_input or "")
    parser.close()
    return parser.ids


def _pick(classes, allowed, default):
    return next((c for c in classes if c in allowed), default)


def sizes_attribute(size_class, natural_width):
    """The <img> sizes attribute for an image block.

    Besides picking the variant, sizes sets the size the browser treats as the
    image's own size, so it must never exceed the natural width (the display
    rules rely on that to never enlarge an image). On phones each size takes a
    share of the screen width (D11).
    """
    desktop = "%dpx" % min(natural_width, DESKTOP_SLOT[size_class])
    vw = MOBILE_SLOT_VW[size_class]
    # Screen width at which the image reaches its natural width.
    limit = natural_width * 100 // vw
    if limit >= MOBILE_BREAKPOINT:
        return "(max-width: %dpx) %dvw, %s" % (MOBILE_BREAKPOINT, vw, desktop)
    return "(max-width: %dpx) %dvw, (max-width: %dpx) %dpx, %s" % (
        limit,
        vw,
        MOBILE_BREAKPOINT,
        natural_width,
        desktop,
    )


def image_style(width, height):
    """The figure's style: natural width (--w) and aspect ratio (--r)."""
    return "--w: %d; --r: %s;" % (
        width,
        f"{width / height:.4f}".rstrip("0").rstrip("."),
    )


def _resolved_block(block, image, request):
    """The block as the server writes it: attributes taken from the stored image."""
    variants = variant_urls(image, request)
    largest = variants[-1]
    size_class = _pick(block.classes, RICH_TEXT_IMAGE_SIZE_CLASSES, DEFAULT_SIZE_CLASS)
    align_class = _pick(
        block.classes, RICH_TEXT_IMAGE_ALIGN_CLASSES, DEFAULT_ALIGN_CLASS
    )
    return RichTextImageBlock(
        classes=[size_class, align_class],
        # Facts about the image only (natural width, aspect ratio); the layout
        # rules that use them are in the frontend CSS.
        style=image_style(largest["width"], largest["height"]),
        image={
            "src": largest["url"],
            "srcset": ", ".join(f"{v['url']} {v['width']}w" for v in variants),
            "sizes": sizes_attribute(size_class, largest["width"]),
            "width": str(largest["width"]),
            "height": str(largest["height"]),
            "alt": (block.image.get("alt") or "").strip()[:MAX_ALT_TEXT_LENGTH],
            "data-image-id": str(image.id),
            "loading": "lazy",
        },
        caption=block.caption,
    )


def resolve_rich_text_images(
    html_input,
    user,
    request,
    project=None,
    field=RichTextImageUsage.PROJECT_DESCRIPTION,
):
    """Sanitise *html_input* and resolve its image blocks against the database.

    An image may be used if *user* owns it or it is already used in this field
    of *project*. Other images are removed. Raises
    :class:`RichTextImageHtmlError` when more than ten images remain.
    """
    cleaned = sanitize_html(
        html_input,
        allowed_tags=PROJECT_DESCRIPTION_ALLOWED_TAGS,
        allowed_attributes=PROJECT_DESCRIPTION_ALLOWED_ATTRIBUTES,
    )
    ids = set(_image_ids(cleaned))
    if not ids:
        return cleaned

    images = RichTextImage.objects.filter(id__in=ids)
    allowed_images = (
        images.filter(owner=user) if user.is_authenticated else images.none()
    )
    if project is not None:
        allowed_images = allowed_images | images.filter(
            usages__project=project, usages__field=field
        )
    by_id = {image.id: image for image in allowed_images.distinct()}

    def _resolve(block):
        image = by_id.get(int(block.image["data-image-id"]))
        if image is None or not image.variants:
            return None
        return _resolved_block(block, image, request)

    # Second pass over the already sanitised HTML, now with the images known.
    resolved = sanitize_html(
        cleaned,
        allowed_tags=PROJECT_DESCRIPTION_ALLOWED_TAGS,
        allowed_attributes=PROJECT_DESCRIPTION_ALLOWED_ATTRIBUTES,
        resolve_image_block=_resolve,
    )

    if count_rich_text_images(resolved) > MAX_IMAGES_PER_TEXT:
        raise RichTextImageHtmlError(
            "A description can contain at most %d images." % MAX_IMAGES_PER_TEXT
        )
    return resolved


def count_rich_text_images(html_input):
    return len(_image_ids(html_input))


def rich_text_image_ids(html_input):
    return set(_image_ids(html_input))


def sync_project_description_usages(project):
    """Record which images the project's description uses, in any language version.

    Reads the saved HTML (not the request), so partial updates and translations
    that were not part of the request are covered too.
    """
    field = RichTextImageUsage.PROJECT_DESCRIPTION
    ids = rich_text_image_ids(project.description_html)
    for translation in project.translation_project.all():
        ids |= rich_text_image_ids(translation.description_html_translation)
    ids = set(RichTextImage.objects.filter(id__in=ids).values_list("id", flat=True))

    usages = RichTextImageUsage.objects.filter(project=project, field=field)
    usages.exclude(image_id__in=ids).delete()
    existing = set(usages.values_list("image_id", flat=True))
    # Ignore rows a concurrent save of the same project has just created.
    RichTextImageUsage.objects.bulk_create(
        [
            RichTextImageUsage(image_id=image_id, project=project, field=field)
            for image_id in ids - existing
        ],
        ignore_conflicts=True,
    )
